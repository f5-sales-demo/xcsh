#!/usr/bin/env bun

/**
 * Pre-compute the HTML template at publish time.
 * This avoids the Bun macro restriction in node_modules.
 */

import { TEMML_CSS } from "../../chat-ui/src/markdown/temml-css.generated";

const adapter = Bun.spawnSync([
	"bun",
	new URL("../../chat-ui/scripts/generate-code-presentation.ts", import.meta.url).pathname,
]);
if (adapter.exitCode !== 0) throw new Error(adapter.stdout.toString() + adapter.stderr.toString());
const { CODE_PANEL_CSS } = await import("../../chat-ui/src/markdown/code-presentation.generated.min.js");
const dir = new URL("../src/export/html/", import.meta.url).pathname;
const mathEntry = new URL("../../chat-ui/src/markdown/math.browser.ts", import.meta.url).pathname;

// Read all files
const html = await Bun.file(`${dir}template.html`).text();
const css = await Bun.file(`${dir}template.css`).text();
const js = await Bun.file(`${dir}template.js`).text();
const marked = await Bun.file(`${dir}vendor/marked.min.js`).text();
const presentationBuild = await Bun.build({
	entrypoints: [new URL("./code-presentation-export.ts", import.meta.url).pathname],
	target: "browser",
	format: "iife",
	minify: true,
});
if (!presentationBuild.success || presentationBuild.outputs.length !== 1)
	throw new AggregateError(presentationBuild.logs, "Code presentation browser build failed");
const notices = await Bun.file(new URL("../../chat-ui/src/markdown/LICENSE.code-presentation", import.meta.url)).text();
const presentation = await presentationBuild.outputs[0].text();

// Preserve Temml's UTF-16 regex string ranges; syntax minification can damage them.
const mathBuild = await Bun.build({
	entrypoints: [mathEntry],
	target: "browser",
	format: "iife",
	minify: false,
});
if (!mathBuild.success || mathBuild.outputs.length !== 1) {
	throw new AggregateError(mathBuild.logs, "Failed to bundle the shared browser math renderer");
}
const math = await mathBuild.outputs[0].text();

// Minify CSS
const minifiedCss = css
	.replace(/\/\*[\s\S]*?\*\//g, "")
	.replace(/\s+/g, " ")
	.replace(/\s*([{}:;,])\s*/g, "$1")
	.trim();

const escapeInlineScript = (source: string): string =>
	source
		.replace(/[\u0080-\uFFFF]/g, character => `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`)
		.replace(/<\/script/gi, "<\\/script");

// Inline everything
const template = html
	.replace(
		"<template-css/>",
		() => `<style>${minifiedCss}</style><style>${CODE_PANEL_CSS}</style><style>${TEMML_CSS}</style>`,
	)
	.replace(
		"<template-vendor-js/>",
		() =>
			`<script>${escapeInlineScript(`${marked}\n/* Bundled dependency notices\n<code-presentation-notices/>\n*/\n${presentation}\n${math}`)}</script>`,
	)
	.replace("<template-js/>", () => `<script>${escapeInlineScript(js)}</script>`);

// Write generated file
const licenseModule = `// Generated dependency notices; preserve required upstream attribution.\nexport const CODE_PRESENTATION_NOTICES = ${JSON.stringify(notices)};\n`;
const licenseFile = `${dir}LICENSE.code-presentation.generated.ts`;
const licenseFormat = Bun.spawnSync(["biome", "check", "--write", "--stdin-file-path", licenseFile], {
	stdin: Buffer.from(licenseModule),
});
if (licenseFormat.exitCode !== 0) throw new Error(licenseFormat.stderr.toString());
await Bun.write(licenseFile, licenseFormat.stdout.toString());
const output = `// Auto-generated by scripts/generate-template.ts - DO NOT EDIT
import { CODE_PRESENTATION_NOTICES } from "./LICENSE.code-presentation.generated";
export const TEMPLATE: string = JSON.parse(${JSON.stringify(JSON.stringify(template))}).replace("<code-presentation-notices/>", () => CODE_PRESENTATION_NOTICES);
`;

const templateFormat = Bun.spawnSync(
	["biome", "check", "--write", "--stdin-file-path", `${dir}template.generated.ts`],
	{ stdin: Buffer.from(output) },
);
if (templateFormat.exitCode !== 0) throw new Error(templateFormat.stderr.toString());
await Bun.write(`${dir}template.generated.ts`, `${templateFormat.stdout.toString().trimEnd()}\n`);
console.log("Generated template.generated.ts");
