/** Bundle the canonical browser policy for clients without workspace dependencies. */
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const source = resolve(import.meta.dir, "../../utils/src/code-presentation.browser.ts");
const dependencyRoot = resolve(import.meta.dir, "../../utils/node_modules");
const notices = `highlight.js 11.11.1\n${await readFile(join(dependencyRoot, "highlight.js/LICENSE"), "utf8")}\nYAML 2.9.0\n${await readFile(join(dependencyRoot, "yaml/LICENSE"), "utf8")}`;
const target = resolve(import.meta.dir, "../src/markdown/code-presentation.generated.min.js");
const build = await Bun.build({ entrypoints: [source], target: "browser", format: "esm", minify: true });
if (!build.success || build.outputs.length !== 1)
	throw new AggregateError(build.logs, "Code presentation bundle failed");
const sources = ["code-presentation.ts", "code-presentation.browser.ts", "../package.json"];
const hash = createHash("sha256");
for (const file of sources) hash.update(await readFile(resolve(source, "..", file)));
const rawBundle = `// biome-ignore-all lint: Generated browser adapter.
// Generated by scripts/generate-code-presentation.ts; source sha256 ${hash.digest("hex")}\n${await build.outputs[0].text()}\n`;
const formatted = Bun.spawnSync(["biome", "format", "--stdin-file-path", target], { stdin: Buffer.from(rawBundle) });
if (formatted.exitCode !== 0) throw new Error(formatted.stderr.toString());
const bundle = formatted.stdout.toString();
const temporary = await mkdtemp(join(tmpdir(), "xcsh-code-types-"));
try {
	const typesProcess = Bun.spawnSync([
		"tsgo",
		"--ignoreConfig",
		source,
		"--declaration",
		"--emitDeclarationOnly",
		"--outDir",
		temporary,
		"--target",
		"ES2022",
		"--lib",
		"ES2024,DOM,DOM.Iterable",
		"--module",
		"ESNext",
		"--moduleResolution",
		"bundler",
		"--skipLibCheck",
		"--strict",
	]);
	if (typesProcess.exitCode !== 0) throw new Error(typesProcess.stdout.toString() + typesProcess.stderr.toString());
	const files = new Map([
		[target, bundle],
		[resolve(target, "..", "LICENSE.code-presentation"), notices],
		[
			target.replace(/\.js$/, ".d.ts"),
			(await readFile(join(temporary, "code-presentation.browser.d.ts"), "utf8")).replace(
				'"./code-presentation"',
				'"./code-presentation.types.generated"',
			),
		],
		[
			target.replace(/\.generated\.min\.js$/, ".types.generated.d.ts"),
			await readFile(join(temporary, "code-presentation.d.ts"), "utf8"),
		],
	]);
	for (const [path, raw] of files) {
		if (path.endsWith("LICENSE.code-presentation")) {
			if (process.argv.includes("--check")) {
				if ((await Bun.file(path).text()) !== raw) throw new Error(`Stale dependency notices: ${path}`);
			} else await Bun.write(path, raw);
			continue;
		}
		const format = Bun.spawnSync(["biome", "check", "--write", "--stdin-file-path", path], {
			stdin: Buffer.from(raw),
		});
		if (format.exitCode !== 0) throw new Error(format.stderr.toString());
		const contents = `${format.stdout.toString().trimEnd()}\n`;
		if (process.argv.includes("--check")) {
			if ((await Bun.file(path).text()) !== contents) throw new Error(`Stale generated adapter: ${path}`);
		} else await Bun.write(path, contents);
	}
} finally {
	await rm(temporary, { recursive: true, force: true });
}
